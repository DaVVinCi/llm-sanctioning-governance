from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pandas as pd

from common import CONDITIONS, OUTPUT_DIR, ROOT, ensure_output_dir, read_csv


REFERENCE_TOLERANCE = 0.02
REFERENCE_VALUES: dict[str, dict[str, float]] = {
    "none": {
        "contribution_ratio": 0.248,
        "payoff_efficiency": 0.749,
        "punishment_frequency": 0.0,
    },
    "broadcast": {
        "contribution_ratio": 0.460,
        "payoff_efficiency": 0.739,
        "punishment_frequency": 0.179,
        "punishment_harm_per_agent_round": 0.100,
        "collateral_share": 0.593,
    },
    "targeted": {
        "contribution_ratio": 0.471,
        "payoff_efficiency": 0.757,
        "punishment_frequency": 0.124,
        "punishment_harm_per_agent_round": 0.060,
        "target_alignment": 0.856,
        "anti_social_punishment_rate": 0.254,
    },
}


def main() -> int:
    ensure_output_dir()
    scripts = [
        "00_audit_data.py",
        "01_compute_metrics.py",
        "02_stats_tests.py",
        "03_reasoning_analysis.py",
        "04_make_figures.py",
    ]
    for script in scripts:
        print(f"Running {script}...")
        subprocess.run([sys.executable, str(ROOT / "analysis" / script)], cwd=ROOT, check=True)

    write_report()
    print("Pipeline complete. See outputs/exploratory_report.md.")
    return 0


def write_report() -> None:
    audit = read_csv(OUTPUT_DIR / "audit_report.csv")
    condition_summary = read_csv(OUTPUT_DIR / "condition_summary.csv")
    model_summary = read_csv(OUTPUT_DIR / "model_condition_summary.csv")
    reasoning = read_csv(OUTPUT_DIR / "reasoning_summary.csv")
    stats = read_csv(OUTPUT_DIR / "stats_results.csv")

    failed = audit[~audit["passed"].astype(bool)]
    formula_failed = failed[
        failed["check_name"].astype(str).str.contains("payoff_formula|incoming_punishment_formula", regex=True, na=False)
    ]
    close_rows = sanity_rows(condition_summary)
    close_ok = all(row["within_tolerance"] for row in close_rows)

    lines: list[str] = []
    lines.append("# Exploratory Reproduction Report")
    lines.append("")
    lines.append("This report is generated by the local reproducible analysis pipeline. It reads only `clean_analysis_data/` and writes derived outputs under `outputs/`.")
    lines.append("")
    lines.append("## Data Audit")
    lines.append("")
    lines.append(f"- Audit checks passed: {len(audit) - len(failed)} / {len(audit)}.")
    lines.append(f"- Required audit status: {'PASS' if failed.empty else 'CHECK FAILURES PRESENT'}.")
    lines.append(f"- Payoff/incoming formula discrepancies: {len(formula_failed)} failed checks.")
    if not formula_failed.empty:
        lines.append("")
        lines.append("| check | condition | model | session | observed | details |")
        lines.append("|---|---|---|---|---:|---|")
        for _, row in formula_failed.head(20).iterrows():
            lines.append(
                f"| {row['check_name']} | {row['condition']} | {row['model']} | {row['session']} | {row['observed']} | {row.get('details', '')} |"
            )
        if len(formula_failed) > 20:
            lines.append(f"| ... | ... | ... | ... | ... | {len(formula_failed) - 20} more failed formula checks |")
    else:
        lines.append("- Payoff and incoming-punishment formulas match within tolerance.")

    lines.append("")
    lines.append("## Condition-Level Results")
    lines.append("")
    lines.append("| condition | CR | PE | PF | cost | harm | collateral | alignment | anti-social |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for condition in CONDITIONS:
        row = condition_summary[condition_summary["condition"] == condition].iloc[0]
        lines.append(
            f"| {condition} | {fmt(row['contribution_ratio'])} | {fmt(row['payoff_efficiency'])} | "
            f"{fmt(row['punishment_frequency'])} | {fmt(row['punishment_cost_per_agent_round'])} | "
            f"{fmt(row['punishment_harm_per_agent_round'])} | {fmt(row['collateral_share'])} | "
            f"{fmt(row['target_alignment'])} | {fmt(row['anti_social_punishment_rate'])} |"
        )

    lines.append("")
    lines.append("Sanity check against the exploratory reference values:")
    lines.append("")
    lines.append("| condition | metric | observed | reference | diff | within 0.02 |")
    lines.append("|---|---|---:|---:|---:|---|")
    for row in close_rows:
        lines.append(
            f"| {row['condition']} | {row['metric']} | {fmt(row['observed'])} | {fmt(row['reference'])} | "
            f"{fmt(row['diff'])} | {'yes' if row['within_tolerance'] else 'no'} |"
        )
    lines.append("")
    lines.append(f"Overall sanity check: {'close to reference values' if close_ok else 'differences require review'}." )

    lines.append("")
    lines.append("## Model-Level Differences")
    lines.append("")
    lines.extend(model_level_summary(model_summary))

    lines.append("")
    lines.append("The threshold-based model labels are exploratory behavioral phenotypes. They are useful for navigation and hypothesis generation, but they are not final confirmatory conclusions.")

    lines.append("")
    lines.append("## Reasoning Text")
    lines.append("")
    lines.append("Keyword-based reasoning analysis is exploratory only. Final paper claims need human annotation or an LLM classifier with human validation.")
    lines.extend(reasoning_summary_lines(reasoning))

    lines.append("")
    lines.append("## Exploratory Statistics")
    lines.append("")
    ok_stats = stats[stats["status"] == "ok"]
    if ok_stats.empty:
        lines.append("- OLS models were skipped or failed; see `stats_results.csv`.")
    else:
        lines.append(f"- OLS rows produced: {len(ok_stats)} coefficient rows across {ok_stats['model_name'].nunique()} models.")
    lines.append("- All regression/OLS outputs are exploratory statistics, not confirmatory evidence. Final paper claims require fixed cleaning rules, fixed metrics, and confirmatory re-analysis.")

    lines.append("")
    lines.append("## Candidate Findings")
    lines.append("")
    lines.extend(candidate_findings(condition_summary, model_summary))

    lines.append("")
    lines.append("## Figure and Table Placement")
    lines.append("")
    lines.append("- Main text: `condition_summary.csv`, selected rows from `model_condition_summary.csv`, Fig. 1 contribution trajectories, Fig. 2 payoff efficiency, and Fig. 3 punishment cost/harm.")
    lines.append("- Main or appendix depending on space: Fig. 4 targeted model phenotypes.")
    lines.append("- Appendix: `audit_report.csv`, `stats_results.csv`, full `model_condition_summary.csv`, `targeted_target_events.csv`, and `reasoning_summary.csv`.")

    lines.append("")
    lines.append("## Confirmatory Analysis Needed")
    lines.append("")
    lines.append("- Freeze cleaning rules, target parsing, low-contributor definition, and phenotype thresholds before final inference.")
    lines.append("- Replace keyword reasoning analysis with human labels or validated classifier labels.")
    lines.append("- Re-run confirmatory models with the final preregistered metric set and report uncertainty consistently.")

    (OUTPUT_DIR / "exploratory_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def sanity_rows(condition_summary: pd.DataFrame) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for condition, refs in REFERENCE_VALUES.items():
        observed_row = condition_summary[condition_summary["condition"] == condition].iloc[0]
        for metric, reference in refs.items():
            observed = float(observed_row[metric])
            diff = observed - reference
            rows.append(
                {
                    "condition": condition,
                    "metric": metric,
                    "observed": observed,
                    "reference": reference,
                    "diff": diff,
                    "within_tolerance": abs(diff) <= REFERENCE_TOLERANCE,
                }
            )
    return rows


def model_level_summary(model_summary: pd.DataFrame) -> list[str]:
    lines: list[str] = []
    targeted = model_summary[model_summary["condition"] == "targeted"].copy()
    broadcast = model_summary[model_summary["condition"] == "broadcast"].copy()
    none = model_summary[model_summary["condition"] == "none"].copy()

    if not targeted.empty:
        top_pe = targeted.sort_values("payoff_efficiency", ascending=False).head(3)
        low_pe = targeted.sort_values("payoff_efficiency", ascending=True).head(3)
        lines.append("- Highest targeted payoff efficiency: " + ", ".join(f"{r.model} ({r.payoff_efficiency:.3f})" for r in top_pe.itertuples()))
        lines.append("- Lowest targeted payoff efficiency: " + ", ".join(f"{r.model} ({r.payoff_efficiency:.3f})" for r in low_pe.itertuples()))
    if not broadcast.empty:
        high_harm = broadcast.sort_values("punishment_harm_per_agent_round", ascending=False).head(3)
        lines.append("- Highest broadcast punishment harm: " + ", ".join(f"{r.model} ({r.punishment_harm_per_agent_round:.3f})" for r in high_harm.itertuples()))
    if not none.empty:
        high_cr = none.sort_values("contribution_ratio", ascending=False).head(3)
        lines.append("- Highest no-punishment contribution ratios: " + ", ".join(f"{r.model} ({r.contribution_ratio:.3f})" for r in high_cr.itertuples()))

    phenotype_rows = model_summary[model_summary["behavioral_phenotypes"] != "unclassified"]
    if not phenotype_rows.empty:
        examples = phenotype_rows[["model", "condition", "behavioral_phenotypes"]].head(8)
        lines.append("- Example exploratory phenotypes: " + "; ".join(f"{r.model}/{r.condition}: {r.behavioral_phenotypes}" for r in examples.itertuples()))
    return lines


def reasoning_summary_lines(reasoning: pd.DataFrame) -> list[str]:
    lines: list[str] = []
    round_rows = reasoning[reasoning["scope"] == "round_agent"]
    for condition in CONDITIONS:
        group = round_rows[round_rows["condition"] == condition].sort_values("share", ascending=False).head(2)
        if not group.empty:
            lines.append(
                "- Top keyword categories in "
                + condition
                + ": "
                + ", ".join(f"{r.reasoning_category} ({r.share:.3f})" for r in group.itertuples())
            )
    event_rows = reasoning[reasoning["scope"] == "targeted_target_events"].sort_values("share", ascending=False).head(3)
    if not event_rows.empty:
        lines.append(
            "- Targeted event reasoning categories most often matched: "
            + ", ".join(f"{r.reasoning_category} ({r.share:.3f})" for r in event_rows.itertuples())
        )
    return lines


def candidate_findings(condition_summary: pd.DataFrame, model_summary: pd.DataFrame) -> list[str]:
    row_b = condition_summary[condition_summary["condition"] == "broadcast"].iloc[0]
    row_t = condition_summary[condition_summary["condition"] == "targeted"].iloc[0]
    row_n = condition_summary[condition_summary["condition"] == "none"].iloc[0]
    lines = [
        (
            f"- Punishment raises cooperation relative to no punishment: CR none={row_n['contribution_ratio']:.3f}, "
            f"broadcast={row_b['contribution_ratio']:.3f}, targeted={row_t['contribution_ratio']:.3f}."
        ),
        (
            f"- Targeted punishment appears more efficient than broadcast in this exploratory pass: "
            f"PE targeted={row_t['payoff_efficiency']:.3f} vs broadcast={row_b['payoff_efficiency']:.3f}, "
            f"harm targeted={row_t['punishment_harm_per_agent_round']:.3f} vs broadcast={row_b['punishment_harm_per_agent_round']:.3f}."
        ),
        (
            f"- Targeted punishment is mostly norm-directed but not purely so: target_alignment={row_t['target_alignment']:.3f}, "
            f"anti_social_punishment_rate={row_t['anti_social_punishment_rate']:.3f}."
        ),
    ]
    targeted = model_summary[model_summary["condition"] == "targeted"]
    if not targeted.empty:
        precise = targeted[targeted["behavioral_phenotypes"].str.contains("precise_norm_enforcer", na=False)]
        punitive = targeted[targeted["behavioral_phenotypes"].str.contains("punitive_but_inefficient|retaliatory_anti_social_punisher", regex=True, na=False)]
        lines.append(f"- Model heterogeneity is large: {len(precise)} targeted model-condition rows are precise norm enforcers, while {len(punitive)} are punitive/anti-social by exploratory thresholds.")
    return lines


def fmt(value: object) -> str:
    if pd.isna(value):
        return ""
    return f"{float(value):.3f}"


if __name__ == "__main__":
    raise SystemExit(main())
